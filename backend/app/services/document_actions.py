def _executive_summary(database: Session, document: Document, data: _ContractData, workspace: str | None) -> tuple[list[dict], list[str]]:
    warnings: list[str] = []
    if not data.is_contract:
        sections, warnings = _workbook_sections(data.workbook)
    else:
        identification = _summary_facts(data, _IDENTIFICATION)
        sections = [
            _section_facts("Contract identification", identification),
            _section_facts("Value and term", _summary_facts(data, _VALUE_TERM)),
        ]
        if not any(fact["value"] for fact in identification):
            warnings.append("No contract identification fields were extracted.")
        analysis = _funding_analysis(data)
        families = data.clause_counts
        clins = len({_clin_key(item.clin) for item in data.line_items if _clin_key(item.clin)})
        glance = [
            {"label": "CLINs / line items", "value": str(clins), "page": None},
            {"label": "Priced total", "value": _money(analysis["priced_total"]), "page": None},
            {"label": "Not-to-exceed (maximum) total", "value": _money(analysis["maximum_total"]), "page": None},
            {"label": "Funded total", "value": _money(analysis["funded_total"]), "page": None},
            {"label": "FAR clauses", "value": str(families.get("FAR", 0)), "page": None},
            {"label": "DFARS clauses", "value": str(families.get("DFARS", 0)), "page": None},
        ]
        other = sum(count for family, count in families.items() if family not in ("FAR", "DFARS"))
        if other:
            glance.append({"label": "Other clauses", "value": str(other), "page": None})
        glance.append({"label": "Performance / delivery records", "value": str(data.period_count), "page": None})
        sections.append(_section_facts("At a glance", glance))

    obligations, warning = _obligations(database, document.id)
    if warning:
        warnings.append(warning)
    if obligations is not None:
        top = sorted(obligations, key=_obligation_sort_key)[:TOP_OBLIGATIONS]
        sections.append(_section_table(
            "Upcoming obligations",
            [("title", "Obligation"), ("due_date", "Due date"), ("status", "Status"), ("page", "Page")],
            [{key: _obligation_row(item)[key] for key in ("title", "due_date", "status", "page")} for item in top],
            empty="No obligations were found in this document.",
        ))

    if data.is_contract:
        playbook, warning = _playbook(database, document.id, workspace)
        if warning:
            warnings.append(warning)
        if playbook is not None and playbook.get("applicable", True):
            summary = playbook.get("summary") or {}
            sections.append(_section_facts("Clause playbook", [
                {"label": "Deviations", "value": str(summary.get("deviations", 0)), "page": None},
                {"label": "High severity", "value": str(summary.get("high", 0)), "page": None},
                {"label": "Medium severity", "value": str(summary.get("medium", 0)), "page": None},
                {"label": "Low severity", "value": str(summary.get("low", 0)), "page": None},
                {"label": "Satisfied", "value": str(summary.get("satisfied", 0)), "page": None},
            ]))

    fields = _review_fields(database, document.id)
    sections.append(_section_facts("Review status", [
        {"label": "Processing", "value": document.processing_status, "page": None},
        {"label": "Fields extracted", "value": str(len(fields)), "page": None},
        {"label": "Pending review", "value": str(sum(1 for f in fields if f.review_status == "pending")), "page": None},
        {"label": f"Below {int(LOW_CONFIDENCE * 100)}% confidence",
         "value": str(sum(1 for f in fields if f.confidence is not None and f.confidence < LOW_CONFIDENCE)), "page": None},
    ]))
    return sections, warnings


_RECOMMENDATIONS = {
    "missing": "Confirm the clause is incorporated, or record the approved exception.",
    "present_prohibited": "Escalate to the contracting officer / legal; request removal or an approved deviation.",
    "present_review": "Review the clause terms against the playbook guidance.",
}


def _risk_register(database: Session, document: Document, data: _ContractData, workspace: str | None) -> tuple[list[dict], list[str]]:
    warnings: list[str] = []
    rows: list[dict] = []

    if data.is_contract:
        playbook, warning = _playbook(database, document.id, workspace)
        if warning:
            warnings.append(warning)
        applicable = playbook is not None and playbook.get("applicable", True)
        for finding in playbook.get("findings", []) if applicable else []:
            status = finding.get("status")
            if status == "satisfied":
                continue
            clause = " ".join(str(part) for part in (finding.get("clause_number"), finding.get("title")) if part)
            label = {
                "missing": "Required clause missing",
                "present_prohibited": "Prohibited clause present",
                "present_review": "Clause flagged for review",
            }.get(status, "Playbook deviation")
            rows.append({
                "risk": f"{label}: {clause}" if clause else label,
                "severity": finding.get("severity") or "medium",
                "source": "Playbook deviation",
                "recommendation": _RECOMMENDATIONS.get(status, "Review against the clause playbook."),
                "page": finding.get("page"),
                "evidence": finding.get("evidence") or finding.get("rationale"),
            })

        for label, lookups in _KEY_FIELDS:
            if not data.fact(*lookups).value:
                rows.append({
                    "risk": f"Missing key field: {label}",
                    "severity": "medium",
                    "source": "Missing key field",
                    "recommendation": "Locate the value on the source document and enter it in Metadata review.",
                    "page": None,
                    "evidence": None,
                })

        for flag in _funding_flags(data, _funding_analysis(data)):
            rows.append({
                "risk": flag["risk"],
                "severity": flag["severity"],
                "source": "Funding gap",
                "recommendation": "Reconcile the CLIN pricing with the funding lines (see Funding reconciliation).",
                "page": flag["page"],
                "evidence": None,
            })

    validation, warning = _validation(database, document.id, workspace, data)
    if warning:
        warnings.append(warning)
    for result in (validation or {}).get("results", []):
        if result.get("status") != "fail":
            continue
        rows.append({
            "risk": f"Validation rule failed: {result.get('name')}",
            "severity": result.get("severity") or "medium",
            "source": "Validation rule",
            "recommendation": result.get("detail") or "Check the value against the rule.",
            "page": result.get("page"),
            "evidence": result.get("value"),
        })

    obligations, warning = _obligations(database, document.id)
    if warning:
        warnings.append(warning)
    for item in obligations or []:
        if item.get("status") == "overdue":
            rows.append({
                "risk": f"Overdue obligation: {item.get('title')}",
                "severity": "high",
                "source": "Obligation",
                "recommendation": "Confirm completion or escalate to the responsible party.",
                "page": item.get("page"),
                "evidence": item.get("evidence"),
            })

    flagged = [
        field for field in _review_fields(database, document.id)
        if field.review_status == "pending" or (field.confidence is not None and field.confidence < LOW_CONFIDENCE)
    ]
    flagged.sort(key=lambda field: (field.confidence if field.confidence is not None else 1.0, field.label or ""))
    for field in flagged[:RISK_FIELD_LIMIT]:
        low = field.confidence is not None and field.confidence < LOW_CONFIDENCE
        reason = f"{round(field.confidence * 100)}% confidence" if low else "pending review"
        rows.append({
            "risk": f"{'Low-confidence' if low else 'Unreviewed'} field: {field.label} ({reason})",
            "severity": "medium" if field.confidence is not None and field.confidence < 0.5 else "low",
            "source": "Low-confidence field" if low else "Pending review",
            "recommendation": "Verify the value against its source page in Metadata review.",
            "page": _page(field.evidence_json),
            "evidence": field.value or None,
        })
    if len(flagged) > RISK_FIELD_LIMIT:
        warnings.append(f"{len(flagged) - RISK_FIELD_LIMIT} more flagged fields are not listed; see the review queue.")

    rows.sort(key=lambda row: _SEVERITY_ORDER.get(str(row["severity"]), 9))
    counts = Counter(str(row["severity"]) for row in rows)
    sections = [
        _section_facts("Summary", [
            {"label": "Risks", "value": str(len(rows)), "page": None},
            {"label": "High", "value": str(counts.get("high", 0)), "page": None},
            {"label": "Medium", "value": str(counts.get("medium", 0)), "page": None},
            {"label": "Low", "value": str(counts.get("low", 0)), "page": None},
        ]),
        _section_table(
            "Risks",
            [("risk", "Risk"), ("severity", "Severity"), ("source", "Source"),
             ("recommendation", "Recommendation"), ("page", "Page"), ("evidence", "Evidence")],
            rows,
            empty="No risks were found in the persisted data for this document.",
        ),
    ]
    return sections, warnings


_GAP_GROUPS = [
    ("missing", "Missing required clauses"),
    ("present_prohibited", "Prohibited clauses present"),
    ("present_review", "Clauses flagged for review"),
    ("satisfied", "Satisfied"),
]


def _clause_gap_report(database: Session, document: Document, data: _ContractData, workspace: str | None) -> tuple[list[dict], list[str]]:
    playbook, warning = _playbook(database, document.id, workspace)
    if playbook is None:
        return [], [warning] if warning else []
    if not playbook.get("applicable", True):
        return [], ["The clause playbook does not apply to this document."]
    findings = playbook.get("findings") or []
    summary = playbook.get("summary") or {}
    sections = [
        _section_facts("Summary", [
            {"label": "Deviations", "value": str(summary.get("deviations", 0)), "page": None},
            {"label": "High severity", "value": str(summary.get("high", 0)), "page": None},
            {"label": "Medium severity", "value": str(summary.get("medium", 0)), "page": None},
            {"label": "Low severity", "value": str(summary.get("low", 0)), "page": None},
            {"label": "Satisfied", "value": str(summary.get("satisfied", 0)), "page": None},
        ])
    ]
    columns = [("clause_number", "Clause"), ("title", "Title"), ("expectation", "Expectation"),
               ("severity", "Severity"), ("rationale", "Rationale"), ("page", "Page"), ("evidence", "Evidence")]
    for status, heading in _GAP_GROUPS:
        group = [finding for finding in findings if finding.get("status") == status]
        group.sort(key=lambda f: (_SEVERITY_ORDER.get(str(f.get("severity")), 9), str(f.get("clause_number") or "")))
        rows = [{key: finding.get(key) for key, _ in columns} for finding in group]
        sections.append(_section_table(heading, columns, rows, empty="None."))
    return sections, []


def _obligations_register(database: Session, document: Document, data: _ContractData, workspace: str | None) -> tuple[list[dict], list[str]]:
    obligations, warning = _obligations(database, document.id)
    if obligations is None:
        return [], [warning] if warning else []
    ordered = sorted(obligations, key=_obligation_sort_key)
    counts = Counter(str(item.get("status") or "unknown") for item in ordered)
    facts = [{"label": "Obligations", "value": str(len(ordered)), "page": None}]
    for status, label in (("overdue", "Overdue"), ("due_soon", "Due soon"), ("upcoming", "Upcoming"), ("ongoing", "Ongoing")):
        facts.append({"label": label, "value": str(counts.get(status, 0)), "page": None})
    return [
        _section_facts("Summary", facts),
        _section_table("Obligations", _OBLIGATION_COLUMNS, [_obligation_row(item) for item in ordered],
                       empty="No obligations were found in this document."),
    ], []


def _funding_reconciliation(database: Session, document: Document, data: _ContractData, workspace: str | None) -> tuple[list[dict], list[str]]:
    analysis = _funding_analysis(data)
    award = data.fact("Award Amount", "Total Award Amount")
    warnings = []
    if data.line_items and not data.funding:
        warnings.append("No funding records were extracted, so CLINs are not reconciled against funding.")
    priced_total, funded_total = analysis["priced_total"], analysis["funded_total"]
    coverage = (
        f"{funded_total / priced_total * 100:.1f}%"
        if priced_total and funded_total is not None
        else None
    )
    facts = [
        {"label": "Priced total (CLINs)", "value": _money(priced_total), "page": None},
        {"label": "Funded total (funding lines)", "value": _money(funded_total), "page": None},
        {"label": "Funding coverage", "value": coverage, "page": None},
        {"label": "Not-to-exceed (maximum) amounts", "value": _money(analysis["maximum_total"]), "page": None},
        {"label": "Funding not tied to a CLIN", "value": _money(analysis["unassigned_funding"]), "page": None},
        {"label": "Award Amount", "value": award.value, "page": award.page},
        {"label": "Ceiling / Max Aggregate", "value": analysis["ceiling_text"], "page": analysis["ceiling_page"]},
        {"label": "Minimum Guarantee", "value": analysis["minimum_text"], "page": analysis["minimum_page"]},
    ]
    if analysis["ceiling_text"] and analysis["ceiling"] is None:
        warnings.append("The ceiling states no dollar amount, so funding is not compared against it.")
    flags = _funding_flags(data, analysis)
    rows = [{key: value for key, value in row.items() if not key.startswith("_")} for row in analysis["rows"]]
    sections = [
        _section_facts("Totals", facts),
        _section_table(
            "By CLIN",
            [("clin", "CLIN"), ("description", "Description"), ("stated", "Amount as stated"),
             ("priced", "Priced"), ("funded", "Funded"),
             ("difference", "Funded − priced"), ("acrn", "ACRN"), ("flag", "Flag"), ("page", "Page")],
            rows,
            empty="No CLINs or funding lines were extracted.",
        ),
        _section_table(
            "Flags",
            [("risk", "Finding"), ("severity", "Severity"), ("page", "Page")],
            flags,
            empty="No funding gaps found.",
        ),
    ]
    return sections, warnings


