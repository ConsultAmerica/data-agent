def _page(evidence: dict | None) -> int | None:
    if not isinstance(evidence, dict):
        return None
    for key in ("page_number", "page", "source_page"):
        value = evidence.get(key)
        if isinstance(value, int) and value > 0:
            return value
    return None


def _evidence_text(evidence: dict | None) -> str | None:
    if not isinstance(evidence, dict):
        return None
    for key in ("source_text", "evidence", "text"):
        value = evidence.get(key)
        if isinstance(value, str) and value.strip():
            return " ".join(value.split())
    return None


def _money(value: float | None) -> str | None:
    return None if value is None else f"${value:,.2f}"


_MONEY_RE = re.compile(r"\$\s?([\d,]+(?:\.\d+)?)\s*(million|billion|m|b)?\b", re.IGNORECASE)


def _parse_money(text: str | None) -> float | None:
    """A dollar amount stated in the text ("$2,500.00", "$47.0M"); None when
    the text states no amount (e.g. "no maximum dollar ceiling")."""

    if not text:
        return None
    match = _MONEY_RE.search(text)
    if not match:
        return None
    try:
        amount = float(match.group(1).replace(",", ""))
    except ValueError:
        return None
    scale = (match.group(2) or "").lower()
    if scale in ("million", "m"):
        amount *= 1_000_000
    elif scale in ("billion", "b"):
        amount *= 1_000_000_000
    return amount


def _clin_key(clin: str | None) -> str | None:
    if not clin or not clin.strip():
        return None
    key = clin.strip().upper().lstrip("0")
    return key or "0"


def _document(database: Session, document_id: str) -> Document:
    document = database.get(Document, str(document_id))
    if document is None:
        raise ValueError("Document not found.")
    return document


_NON_ALNUM = re.compile(r"[^a-z0-9]+")


def _norm(label: str) -> str:
    return _NON_ALNUM.sub("", label.lower())


def _cell_page(cell) -> int | None:
    provenance = getattr(cell, "provenance", None)
    page = getattr(provenance, "source_page", None)
    return page if isinstance(page, int) and page > 0 else None


def _cell_text(cell) -> str | None:
    if cell is None or cell.value is None:
        return None
    text = str(cell.value).strip()
    return text or None


def _find_cell(record, *suffixes: str):
    """The record's cell whose canonical field ends with one of `suffixes`
    (``contract.line.amount`` -> "amount"), in the order given."""

    for suffix in suffixes:
        for field, cell in record.cells.items():
            if field == suffix or field.endswith("." + suffix):
                return cell
    return None


_PLAIN_NUMBER_RE = re.compile(r"^\s*\(?-?[\d,]+(?:\.\d+)?\)?\s*$")


def _parse_amount(value) -> float | None:
    """A workbook amount cell: a number, "$1,234.00", "$600,000,000.00 NTE";
    None for "NSP", "UNDEFINED" and other statements without a figure."""

    if value is None or isinstance(value, bool):
        return None
    if isinstance(value, (int, float)):
        return float(value)
    text = str(value)
    amount = _parse_money(text)
    if amount is not None:
        return amount
    if _PLAIN_NUMBER_RE.match(text):
        try:
            return float(text.strip().strip("()").replace(",", ""))
        except ValueError:
            return None
    return None


def _first_line(text: str | None) -> str | None:
    if not text:
        return None
    return text.strip().splitlines()[0].strip() or None


