def _workbook_sections(workbook) -> tuple[list[dict], list[str]]:
    if workbook is None:
        return [], ["The staging workbook is not available for this document yet."]

    sections: list[dict] = []
    by_id = {dataset.dataset_id: dataset for dataset in workbook.datasets}
    summary = by_id.get("document_summary")
    if summary is not None and summary.records:
        facts = []
        for cell in summary.records[0].cells.values():
            facts.append({
                "label": cell.display_label,
                "value": None if cell.value is None else str(cell.value),
                "page": cell.provenance.source_page if cell.provenance else None,
            })
        sections.append(_section_facts("Document", facts))

    fields = by_id.get("key_fields") or by_id.get("all_fields")
    if fields is not None and fields.records:
        rows = []
        for record in fields.records[:50]:
            name = record.cells.get("name")
            value = record.cells.get("value")
            provenance = (value.provenance if value else None) or (name.provenance if name else None)
            rows.append({
                "field": None if name is None or name.value is None else str(name.value),
                "value": None if value is None or value.value is None else str(value.value),
                "status": record.record_status,
                "page": provenance.source_page if provenance else None,
            })
        sections.append(_section_table(
            "Key fields", [("field", "Field"), ("value", "Value"), ("status", "Status"), ("page", "Page")], rows,
        ))

    qa = workbook.qa_summary
    sections.append(_section_facts("Staging review", [
        {"label": "Records", "value": str(qa.record_count), "page": None},
        {"label": "Verified", "value": str(qa.verified), "page": None},
        {"label": "Needs review", "value": str(qa.needs_review), "page": None},
        {"label": "Missing", "value": str(qa.missing), "page": None},
    ]))
    return sections, []


