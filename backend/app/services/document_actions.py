def _summary_facts(data: _ContractData, fields: list[tuple[str, tuple[str, ...]]]) -> list[dict]:
    facts = []
    for label, lookups in fields:
        fact = data.fact(*lookups)
        facts.append({"label": label, "value": fact.value, "page": fact.page if fact.value else None})
    return facts


def _section_facts(heading: str, facts: list[dict]) -> dict:
    return {"heading": heading, "kind": "facts", "facts": facts}


def _section_table(heading: str, columns: list[tuple[str, str]], rows: list[dict], empty: str | None = None) -> dict:
    section = {
        "heading": heading,
        "kind": "table",
        "columns": [{"key": key, "label": label} for key, label in columns],
        "rows": rows,
    }
    if empty and not rows:
        section["empty_message"] = empty
    return section


