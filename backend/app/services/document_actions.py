def _funding_analysis(data: _ContractData) -> dict:
    priced: dict[str, dict] = {}
    maximum_total = 0.0
    for item in data.line_items:
        key = _clin_key(item.clin)
        if item.amount is not None and item.is_maximum:
            maximum_total += item.amount
        if key is None:
            continue
        entry = priced.setdefault(
            key,
            {"clin": item.clin.strip(), "description": item.description, "priced": 0.0,
             "has_price": False, "maximum": False, "stated": [], "page": item.page},
        )
        if item.amount is not None and not item.is_maximum:
            entry["priced"] += item.amount
            entry["has_price"] = True
        if item.is_maximum:
            entry["maximum"] = True
        if item.amount_text:
            entry["stated"].append(item.amount_text)

    funded: dict[str, dict] = {}
    unassigned_funding = 0.0
    for line in data.funding:
        key = _clin_key(line.clin)
        amount = line.amount or 0.0
        if key is None:
            unassigned_funding += amount
            continue
        entry = funded.setdefault(key, {"clin": line.clin.strip(), "funded": 0.0, "acrns": [], "page": line.page})
        entry["funded"] += amount
        if line.acrn:
            entry["acrns"].append(line.acrn)

    rows = []
    for key in sorted(set(priced) | set(funded), key=lambda k: (len(k), k)):
        price = priced.get(key)
        fund = funded.get(key)
        priced_amount = price["priced"] if price and price["has_price"] else None
        funded_amount = fund["funded"] if fund else None
        if price is None:
            flag = "Funding without a priced CLIN"
        elif priced_amount is None:
            flag = "Not-to-exceed only" if price["maximum"] else "No price stated"
        elif not data.funding:
            # Nothing to reconcile against (e.g. an IDIQ base award obligates no funds).
            flag = "No funding extracted"
        elif priced_amount > 0 and not funded_amount:
            flag = "Unfunded"
        elif funded_amount is not None and funded_amount > priced_amount + 0.005:
            flag = "Overfunded"
        elif funded_amount is not None and priced_amount > 0 and funded_amount + 0.005 < priced_amount:
            flag = "Partially funded"
        elif funded_amount is not None:
            flag = "Funded"
        else:
            flag = "No funding required"
        difference = (
            funded_amount - priced_amount
            if funded_amount is not None and priced_amount is not None
            else None
        )
        rows.append({
            "clin": (price or fund)["clin"],
            "description": price["description"] if price else None,
            "stated": "; ".join(price["stated"]) if price and price["stated"] else None,
            "priced": _money(priced_amount),
            "funded": _money(funded_amount),
            "difference": _money(difference),
            "acrn": ", ".join(fund["acrns"]) if fund and fund["acrns"] else None,
            "flag": flag,
            "page": (price or {}).get("page") or (fund or {}).get("page"),
            "_priced": priced_amount,
            "_funded": funded_amount,
        })

    priced_total = sum(entry["priced"] for entry in priced.values() if entry["has_price"])
    # Funding lines without a CLIN still count toward the funded total.
    funded_total = sum(line.amount or 0.0 for line in data.funding)
    ceiling, minimum = data.fact(*_CEILING), data.fact(*_MINIMUM)
    ceiling_text, minimum_text = ceiling.value, minimum.value
    return {
        "rows": rows,
        "priced_total": priced_total if any(entry["has_price"] for entry in priced.values()) else None,
        "funded_total": funded_total if data.funding else None,
        "maximum_total": maximum_total or None,
        "unassigned_funding": unassigned_funding or None,
        "ceiling_text": ceiling_text,
        "ceiling": _parse_money(ceiling_text),
        "ceiling_page": ceiling.page,
        "minimum_text": minimum_text,
        "minimum": _parse_money(minimum_text),
        "minimum_page": minimum.page,
    }


def funding_totals(data: _ContractData) -> dict:
    """Priced, not-to-exceed and funded totals (None when not stated), for
    other services that check the same reconciliation the report shows."""

    analysis = _funding_analysis(data)
    return {
        "priced_total": analysis["priced_total"],
        "maximum_total": analysis["maximum_total"],
        "funded_total": analysis["funded_total"],
    }


def parse_money(text: str | None) -> float | None:
    """Public form of the reports' dollar-amount parsing."""

    return _parse_money(text)


def _funding_flags(data: _ContractData, analysis: dict) -> list[dict]:
    """Funding gaps as risk-register rows."""

    flags = []
    for row in analysis["rows"]:
        if row["flag"] == "Unfunded":
            flags.append({"risk": f"CLIN {row['clin']} is priced ({row['priced']}) but has no funding line",
                          "severity": "high", "page": row["page"]})
        elif row["flag"] == "Overfunded":
            flags.append({"risk": f"CLIN {row['clin']} is funded above its priced amount ({row['funded']} vs {row['priced']})",
                          "severity": "medium", "page": row["page"]})
        elif row["flag"] == "Funding without a priced CLIN":
            flags.append({"risk": f"Funding on CLIN {row['clin']} ({row['funded']}) has no matching priced CLIN",
                          "severity": "medium", "page": row["page"]})
    funded_total, ceiling, minimum = analysis["funded_total"], analysis["ceiling"], analysis["minimum"]
    if funded_total is not None and ceiling is not None and funded_total > ceiling:
        flags.append({"risk": f"Funded total {_money(funded_total)} exceeds the stated ceiling {_money(ceiling)}",
                      "severity": "high", "page": analysis["ceiling_page"]})
    if funded_total is not None and minimum is not None and funded_total < minimum:
        flags.append({"risk": f"Funded total {_money(funded_total)} is below the minimum guarantee {_money(minimum)}",
                      "severity": "low", "page": analysis["minimum_page"]})
    return flags


