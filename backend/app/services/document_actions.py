class _ContractData:
    """One document's contract data. The persisted Professional Staging
    Workbook (what the document page shows) is the primary source; the V3
    extraction tables fill only what the workbook lacks, per field and per
    category."""

    def __init__(self, database: Session, document_id: str) -> None:
        self.workbook = self._load_workbook(database, document_id)
        self._datasets = {dataset.dataset_id: dataset for dataset in self.workbook.datasets} if self.workbook else {}
        self.v3_summary = database.scalars(
            select(DocumentContractSummary).where(DocumentContractSummary.document_id == document_id)
        ).first()
        self._facts: dict[str, _Fact] = {}
        self._index_workbook_facts()
        self._index_v3_facts()

        self.line_items = self._workbook_lines()
        if not self.line_items:
            self.line_items = [
                _Line(item.clin, item.description, item.amount, bool(item.is_maximum),
                      _money(item.amount), _page(item.evidence_json))
                for item in database.scalars(
                    select(DocumentLineItem)
                    .where(DocumentLineItem.document_id == document_id)
                    .order_by(DocumentLineItem.row_index)
                )
            ]
        self.funding = self._workbook_funding()
        if not self.funding:
            self.funding = [
                _Fund(line.clin, line.acrn, line.amount, _page(line.evidence_json))
                for line in database.scalars(
                    select(DocumentFundingLine)
                    .where(DocumentFundingLine.document_id == document_id)
                    .order_by(DocumentFundingLine.row_index)
                )
            ]
        self.clause_counts = self._workbook_clause_counts() or self._v3_clause_counts(database, document_id)
        self.period_count = self._records_count("performance_delivery")
        if self.period_count is None:
            self.period_count = len(list(database.scalars(
                select(DocumentPerformancePeriod.id).where(DocumentPerformancePeriod.document_id == document_id)
            )))

    @staticmethod
    def _load_workbook(database: Session, document_id: str):
        try:
            from app.staging.service import get_staging_workbook

            return get_staging_workbook(database, document_id)
        except Exception:  # noqa: BLE001 - reports fall back to the V3 tables
            logger.exception("staging workbook unavailable for %s", document_id)
            return None

    def _records(self, dataset_id: str) -> list:
        dataset = self._datasets.get(dataset_id)
        return list(dataset.records) if dataset is not None else []

    def _records_count(self, dataset_id: str) -> int | None:
        dataset = self._datasets.get(dataset_id)
        return len(dataset.records) if dataset is not None and dataset.records else None

    def _remember(self, label: str | None, value: str | None, page: int | None) -> None:
        if not label or not value:
            return
        self._facts.setdefault(_norm(label), _Fact(value, page))

    def _index_workbook_facts(self) -> None:
        # The Contract Summary tab first (exactly what the user sees), then
        # the summary record, then the source-labelled Contract Details.
        for record in self._records("contract_overview"):
            label = _cell_text(_find_cell(record, "label"))
            value_cell = _find_cell(record, "value")
            self._remember(label, _cell_text(value_cell), _cell_page(value_cell))
        for record in self._records("contract_summary"):
            for cell in record.cells.values():
                self._remember(cell.display_label, _cell_text(cell), _cell_page(cell))
        for record in self._records("contract_details"):
            value_cell = _find_cell(record, "value")
            value, page = _cell_text(value_cell), _cell_page(value_cell)
            field_id = _cell_text(_find_cell(record, "field_id"))
            if field_id:
                self._remember(field_id.rsplit(".", 1)[-1], value, page)
            self._remember(_cell_text(_find_cell(record, "label")), value, page)

    def _index_v3_facts(self) -> None:
        if self.v3_summary is None:
            return
        provenance = self.v3_summary.field_provenance_json or {}
        for attribute, label in _V3_SUMMARY_LABELS:
            entry = provenance.get(label)
            page = entry.get("page") if isinstance(entry, dict) else None
            self._remember(label, getattr(self.v3_summary, attribute, None), page if isinstance(page, int) else None)

    def fact(self, *labels: str) -> _Fact:
        for label in labels:
            found = self._facts.get(_norm(label))
            if found is not None:
                return found
        return _Fact(None, None)

    def overview_count(self, label: str) -> int | None:
        found = self._facts.get(_norm(label))
        if found is None or found.value is None:
            return None
        try:
            return int(str(found.value).replace(",", ""))
        except ValueError:
            return None

    def _workbook_lines(self) -> list[_Line]:
        # The CLIN schedule as staged: dedicated CLIN records, else the
        # schedule's line items, else the Contract Data CLIN rows.
        sources = [
            (self._records("clins"), ("clin",), ("description",), ("max_amount", "amount")),
            (self._records("line_items"), ("item_number", "clin"), ("description",), ("amount",)),
            ([record for record in self._records("contract_data")
              if (_cell_text(_find_cell(record, "record_type")) or "").upper() == "CLIN"],
             ("clin", "record_id"), ("title", "value"), ("amount",)),
        ]
        for records, clin_fields, description_fields, amount_fields in sources:
            lines = []
            for record in records:
                clin_cell = _find_cell(record, *clin_fields)
                amount_cell = _find_cell(record, *amount_fields)
                amount_text = _cell_text(amount_cell)
                column = (amount_cell.display_label if amount_cell else "") or ""
                amount = _parse_amount(amount_cell.value if amount_cell else None)
                # A maximum needs a figure: "NSP" under MAX AMOUNT is no price at all.
                is_maximum = amount is not None and (
                    amount_cell.canonical_field.endswith("max_amount")
                    or "NTE" in (amount_text or "").upper()
                    or "MAX" in column.upper()
                )
                lines.append(_Line(
                    clin=_cell_text(clin_cell),
                    description=_first_line(_cell_text(_find_cell(record, *description_fields))),
                    amount=amount,
                    is_maximum=is_maximum,
                    amount_text=amount_text,
                    page=_cell_page(amount_cell) or _cell_page(clin_cell),
                ))
            if lines:
                return lines
        return []

    def _workbook_funding(self) -> list[_Fund]:
        records = self._records("funding") or [
            record for record in self._records("contract_data")
            if "FUNDING" in (_cell_text(_find_cell(record, "record_type")) or "").upper()
        ]
        funds = []
        for record in records:
            amount_cell = _find_cell(record, "amount")
            funds.append(_Fund(
                clin=_cell_text(_find_cell(record, "clin")),
                acrn=_cell_text(_find_cell(record, "acrn", "funding_level")),
                amount=_parse_amount(amount_cell.value if amount_cell else None),
                page=_cell_page(amount_cell),
            ))
        return funds

    def _workbook_clause_counts(self) -> Counter | None:
        far, dfars = self.overview_count("FAR Clauses"), self.overview_count("DFARS Clauses")
        if far is not None or dfars is not None:
            return Counter({"FAR": far or 0, "DFARS": dfars or 0})
        counts: Counter = Counter()
        seen = set()
        for record in self._records("contract_clauses") or self._records("clauses") + self._records("dfars"):
            number = _cell_text(_find_cell(record, "clause_number")) or ""
            regulation = (_cell_text(_find_cell(record, "regulation")) or "").upper()
            if "DFARS" in regulation or number.startswith("252."):
                family = "DFARS"
            elif "FAR" in regulation or number.startswith("52."):
                family = "FAR"
            else:
                family = "OTHER"
            if (family, number) in seen:
                continue
            seen.add((family, number))
            counts[family] += 1
        return counts or None

    @staticmethod
    def _v3_clause_counts(database: Session, document_id: str) -> Counter:
        counts: Counter = Counter()
        seen = set()
        for family, number in database.execute(
            select(DocumentClauseReference.clause_family, DocumentClauseReference.clause_number)
            .where(DocumentClauseReference.document_id == document_id)
        ):
            key = ((family or "Other").upper(), number)
            if key in seen:
                continue
            seen.add(key)
            counts[key[0]] += 1
        return counts

    @property
    def is_contract(self) -> bool:
        profile_id = self.workbook.profile.profile_id if self.workbook else ""
        return bool(
            profile_id.startswith("contract")
            or "contract_overview" in self._datasets
            or self.v3_summary
            or self.line_items
            or self.funding
            or sum(self.clause_counts.values())
        )


def load_contract_data(database: Session, document_id: str) -> _ContractData:
    """One document's contract facts (staging workbook first, V3 fallback),
    for other services that cite the same values the reports do."""

    return _ContractData(database, document_id)


